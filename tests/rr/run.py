#!/usr/bin/env python3
"""Run rr's test programs under `ffs record` + `ffs replay`.

rr's test suite (src/test/*.c in an rr checkout) is a large corpus of
programs that exercise Linux syscalls, signals, threads and process
semantics, each printing a token (usually EXIT-SUCCESS) when it passed and
designed so that record and replay must produce identical output.  This
driver builds every test listed in tests.tsv against rr's own util.h,
records it under ffs, replays the trace, and classifies the result:

  BUILD_FAIL        the test does not compile here
  REC_TIMEOUT       recording did not finish within the timeout
  REC_ERROR         ffs itself failed while recording
  REC_DEADLOCK      ffs reported a deadlock (every thread blocked)
  REC_NOTOKEN       the program ran but did not print its success token
                    (its own checks failed, or it needs an rr feature)
  REPLAY_TIMEOUT    replay did not finish
  REPLAY_ERROR      ffs failed while replaying
  REPLAY_DIVERGED   the replayed events differ from the trace
  REPLAY_SHORT      replay ended before the end of the trace
  OUTPUT_MISMATCH   stdout of record and replay differ
  STRICT_DIVERGED   the second replay diverged; --strict is a compatibility
                    alias, so both passes now use the same checks
  PASS

Usage: run.py [--rr DIR] [--ffs BIN] [--out DIR] [-j N] [--only a,b,...] [--verify-outputs]
"""
import argparse, os, re, shutil, subprocess, sys, threading, time
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
CFLAGS = ['-std=gnu11', '-g', '-O0', '-D_GNU_SOURCE', '-U_FORTIFY_SOURCE', '-Wno-cpp', '-w']
LIBS = ['-lrt', '-ldl', '-lpthread', '-lm', '-lutil']


def read_tests(path):
    rows = []
    for line in open(path):
        if not line.strip() or line.startswith('#'):
            continue
        f = (line.rstrip('\n').split('\t') + [''] * 7)[:7]
        rows.append(dict(name=f[0], src=f[1], token=f[2], args=f[3], sig=f[4],
                         timeout=int(f[5] or 120), kind=f[6]))
    return rows


def generate_headers(rr, gendir):
    """rr's util.h includes syscall enums generated by src/generate_syscalls.py."""
    os.makedirs(gendir, exist_ok=True)
    for name in ('SyscallEnumsForTestsX64', 'SyscallEnumsForTestsX86', 'SyscallEnumsForTestsGeneric'):
        out = os.path.join(gendir, name + '.generated')
        if not os.path.exists(out):
            subprocess.run([sys.executable, os.path.join(rr, 'src', 'generate_syscalls.py'), out],
                           check=True, cwd=os.path.join(rr, 'src'))


def build(t, rr, bindir, log):
    gendir = os.path.join(os.path.dirname(bindir), 'gen')
    src = os.path.join(rr, 'src', 'test', t['src'] + '.c')
    cc = 'gcc'
    if not os.path.exists(src):
        src = os.path.join(rr, 'src', 'test', t['src'] + '.cc')
        cc = 'g++'
    if not os.path.exists(src):
        return 'no source'
    out = os.path.join(bindir, t['name'])
    if os.path.exists(out) and os.path.getmtime(out) > os.path.getmtime(src):
        return None
    inc = ['-I' + os.path.join(rr, 'src', 'test'), '-I' + os.path.join(rr, 'include'),
           '-I' + os.path.join(rr, 'src', 'preload'), '-I' + gendir]
    cmd = [cc] + (CFLAGS if cc == 'gcc' else ['-g', '-O0', '-D_GNU_SOURCE', '-w']) + inc + ['-o', out, src] + LIBS
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        err = p.stderr.strip().splitlines()
        err = next((l for l in err if 'error' in l), err[-1] if err else '?')
        log.write(f"== {t['name']}\n{' '.join(cmd)}\n{p.stderr}\n")
        return err
    return None


def run_cmd(cmd, timeout, cwd, out, err, env):
    # A new session: tests do things like kill(0, SIGABRT), which would
    # otherwise reach the harness.
    with open(out, 'w') as fo, open(err, 'w') as fe:
        try:
            p = subprocess.run(cmd, cwd=cwd, stdout=fo, stderr=fe, stdin=subprocess.DEVNULL,
                               env=env, timeout=timeout, start_new_session=True)
            return p.returncode
        except subprocess.TimeoutExpired:
            return 124


def signal_thread(spec, exe_name, record_out):
    sig, delay, ready = spec.split(':')
    sig, delay = int(sig), float(delay)
    time.sleep(delay)
    deadline = time.time() + 30
    while time.time() < deadline:
        try:
            if ready in open(record_out).read():
                break
        except OSError:
            pass
        time.sleep(0.01)
    p = subprocess.run(['pidof', exe_name], capture_output=True, text=True)
    pids = p.stdout.split()
    if len(pids) == 1:
        subprocess.run(['kill', f'-{sig}', pids[0]])


def last_ffs_line(path, pat='error|DIVERGED|DEADLOCK|expected|actual'):
    try:
        lines = [l.rstrip() for l in open(path, errors='replace') if l.startswith('[ffs]') or 'expected' in l or 'actual' in l]
    except OSError:
        return ''
    hits = [l for l in lines if re.search(pat, l)]
    return ' | '.join(hits[-3:])[:300] if hits else (lines[-1][:200] if lines else '')


def replay_status(rc, errpath):
    err = open(errpath, errors='replace').read()
    if rc == 124:
        return 'REPLAY_TIMEOUT', ''
    if 'REPLAY DIVERGED' in err:
        return 'REPLAY_DIVERGED', last_ffs_line(errpath)
    m = re.search(r'replayed (\d+) of (\d+) steps', err)
    if 'replayed all' in err:
        return None, ''
    if m and m.group(1) == m.group(2):
        return None, ''
    if rc == 70 or '[ffs] error' in err:
        return 'REPLAY_ERROR', last_ffs_line(errpath)
    return 'REPLAY_SHORT', (m.group(0) if m else '') + ' ' + last_ffs_line(errpath)


def run_test(t, a, bindir, workroot, nonce):
    wd = os.path.join(workroot, t['name'])
    shutil.rmtree(wd, ignore_errors=True)
    os.makedirs(wd)
    exe_name = f"{t['name']}-{nonce}"
    exe = os.path.join(wd, exe_name)
    shutil.copy(os.path.join(bindir, t['name']), exe)
    args = []
    for x in t['args'].split():
        m = re.match(r'\{exe:(\w+)\}', x)
        if m:
            x = os.path.join(bindir, m.group(1))
        args.append(x.replace('{pwd}', wd))
    env = dict(os.environ, LC_ALL='C', NONTMP_WORKDIR=wd)
    ffs = [a.ffs]
    extra = a.ffs_args
    replay_extra = extra + (['--verify-outputs'] if a.verify_outputs else [])
    rec = os.path.join(wd, 'record.out')
    th = None
    if t['sig']:
        th = threading.Thread(target=signal_thread, args=(t['sig'], exe_name, rec), daemon=True)
        th.start()
    rc = run_cmd(ffs + ['record'] + extra + ['-o', 'trace.json', '--', './' + exe_name] + args,
                 t['timeout'], wd, rec, os.path.join(wd, 'record.err'), env)
    if th:
        th.join(timeout=60)
    rec_err = os.path.join(wd, 'record.err')
    errtxt = open(rec_err, errors='replace').read()
    if rc == 124:
        return 'REC_TIMEOUT', last_ffs_line(rec_err, '.')
    if rc == 70 or '[ffs] error' in errtxt:
        return 'REC_ERROR', last_ffs_line(rec_err)
    if 'DEADLOCK' in errtxt:
        return 'REC_DEADLOCK', last_ffs_line(rec_err)
    out = open(rec, errors='replace').read()
    # rr's harness greps for the token (a basic regular expression: only
    # '.' is special in the tokens used).
    tok = re.escape(t['token']).replace(r'\.', '.')
    if t['token'] and not re.search(tok, out):
        tail = out.strip().splitlines()[-1][:120] if out.strip() else '(no output)'
        return 'REC_NOTOKEN', f'exit={rc} last="{tail}"'
    if not os.path.exists(os.path.join(wd, 'trace.json')):
        return 'REC_ERROR', 'no trace written'
    rc = run_cmd(ffs + ['replay'] + replay_extra + ['trace.json'], t['timeout'], wd,
                 os.path.join(wd, 'replay.out'), os.path.join(wd, 'replay.err'), env)
    st, detail = replay_status(rc, os.path.join(wd, 'replay.err'))
    if st:
        return st, detail
    if open(os.path.join(wd, 'replay.out'), errors='replace').read() != out:
        return 'OUTPUT_MISMATCH', ''
    rc = run_cmd(ffs + ['replay', '--strict'] + replay_extra + ['trace.json'], t['timeout'], wd,
                 os.path.join(wd, 'strict.out'), os.path.join(wd, 'strict.err'), env)
    st, detail = replay_status(rc, os.path.join(wd, 'strict.err'))
    if st:
        return 'STRICT_' + st.replace('REPLAY_', ''), detail
    return 'PASS', ''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rr', default=os.environ.get('RR_SRC', os.path.expanduser('~/repos/rr')))
    ap.add_argument('--ffs', default=os.path.join(HERE, '..', '..', 'target', 'release', 'ffs'))
    ap.add_argument('--verify-outputs', action='store_true', help='verify captured output buffers on both replay passes')
    ap.add_argument('--ffs-args', default='', help='extra options for ffs record/replay')
    ap.add_argument('--out', default=os.path.join(HERE, 'out'))
    ap.add_argument('-j', type=int, default=max(1, (os.cpu_count() or 2) // 2))
    ap.add_argument('--only', default='')
    ap.add_argument('--kind', default='')
    ap.add_argument('--tests', default=os.path.join(HERE, 'tests.tsv'))
    a = ap.parse_args()
    a.ffs = os.path.abspath(a.ffs)
    a.ffs_args = a.ffs_args.split()
    tests = read_tests(a.tests)
    only = set(a.only.split(',')) if a.only else None
    bindir = os.path.join(a.out, 'bin')
    workroot = os.path.join(a.out, 'work')
    os.makedirs(bindir, exist_ok=True)
    os.makedirs(workroot, exist_ok=True)
    nonce = str(os.getpid())
    results = {}
    lock = threading.Lock()
    blog = open(os.path.join(a.out, 'build.log'), 'w')
    generate_headers(a.rr, os.path.join(a.out, 'gen'))
    todo = [t for t in tests if (not only or t['name'] in only) and (not a.kind or t['kind'] == a.kind)]
    # Build everything first (helpers included).
    with ThreadPoolExecutor(a.j) as ex:
        for t, err in zip(tests, ex.map(lambda t: build(t, a.rr, bindir, blog), tests)):
            if err:
                results[t['name']] = ('BUILD_FAIL', err[:200])
    blog.close()

    def one(t):
        if t['name'] in results or t['kind'] == 'helper':
            return
        try:
            st, detail = run_test(t, a, bindir, workroot, nonce)
        except Exception as e:  # harness bug, not a test result
            st, detail = 'HARNESS_ERROR', repr(e)[:200]
        with lock:
            results[t['name']] = (st, detail)
            n = sum(1 for x in todo if x["name"] in results)
            print(f'[{n}/{len(todo)}] {t["name"]}: {st} {detail}', flush=True)

    with ThreadPoolExecutor(a.j) as ex:
        list(ex.map(one, todo))
    with open(os.path.join(a.out, 'results.tsv'), 'w') as f:
        for t in todo:
            st, detail = results.get(t['name'], ('SKIPPED', ''))
            f.write(f"{t['name']}\t{st}\t{detail}\n")
    counts = {}
    for t in todo:
        st = results.get(t['name'], ('SKIPPED', ''))[0]
        counts[st] = counts.get(st, 0) + 1
    print('\nsummary:')
    for k, v in sorted(counts.items(), key=lambda kv: -kv[1]):
        print(f'  {k:18} {v}')
    print(f'  {"total":18} {len(todo)}')


if __name__ == '__main__':
    main()
